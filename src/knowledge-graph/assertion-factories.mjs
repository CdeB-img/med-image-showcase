import {
  SCIENTIFIC_ASSERTION_LAYER_VERSION,
  SCIENTIFIC_ASSERTION_NAMESPACE,
} from "./assertion-schema.mjs";

const deepFreeze = (value) => {
  if (!value || typeof value !== "object") return value;
  if (Array.isArray(value)) return Object.freeze(value.map(deepFreeze));
  return Object.freeze(Object.fromEntries(Object.entries(value).map(([key, nested]) => [key, deepFreeze(nested)])));
};

const timestamp = () => new Date().toISOString();
const copyArray = (value = []) => [...value];

export const scientificAssertionId = (slug) => `${SCIENTIFIC_ASSERTION_NAMESPACE}:${slug}`;

export const createAssertionContextVariant = ({
  contextId,
  population = null,
  clinicalContext = null,
  technicalContext = null,
  workflowContext = null,
  equipmentContext = null,
  softwareContext = null,
  sequenceContext = null,
  fieldStrength = null,
  contrastAgent = null,
  measurementMethod = null,
} = {}) => deepFreeze({
  contextId,
  population,
  clinicalContext,
  technicalContext,
  workflowContext,
  equipmentContext,
  softwareContext,
  sequenceContext,
  fieldStrength,
  contrastAgent,
  measurementMethod,
});

export const createAssertionContext = ({
  scope = "UNSPECIFIED",
  includeEntityIds = [],
  excludeEntityIds = [],
  tags = [],
  combination = "ANY_OF",
  variants = [],
} = {}) => deepFreeze({
  scope,
  includeEntityIds: copyArray(includeEntityIds),
  excludeEntityIds: copyArray(excludeEntityIds),
  tags: copyArray(tags),
  combination,
  variants: copyArray(variants),
});

